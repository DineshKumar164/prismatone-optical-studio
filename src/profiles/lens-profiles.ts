import { CalibrationAccuracyLevel } from './film-profiles';

export interface LensProfile {
  id: string;
  manufacturer: string;
  model: string;
  opticalType:
    | 'Spherical'
    | 'Vintage Spherical'
    | 'Anamorphic 2x'
    | 'Anamorphic 1.8x'
    | 'Anamorphic 1.5x'
    | 'Anamorphic 1.33x';
  // 3.1 Optical Geometry
  focalLengthMm: number;
  zoomRangeMm: [number, number] | null;
  maxApertureTStop: number;
  minApertureTStop: number;
  transmissionEfficiencyPct: number; // e.g. 92% for modern T*, 78% for vintage uncoated
  imageCircleMm: number; // e.g. 31.1mm S35, 46.3mm Full Frame / VV
  mountType: 'PL' | 'LPL' | 'PV' | 'EF Cine';
  sensorFormatCoverage: 'Super 35' | 'Full Frame / VistaVision' | '65mm Large Format';
  closeFocusM: number;
  anamorphicSqueeze: number; // 1.0, 1.33, 1.5, 1.8, 2.0
  distortionK1: number; // Radial Brown-Conrady k1 (- barrel, + pincushion)
  distortionK2: number; // Radial Brown-Conrady k2
  fieldCurvature: number; // 0..1 Petzval field curvature
  vignettingAmount: number; // 0..1
  vignettingFalloff: number; // 0.8..3.0
  // 3.2 & 3.3 Optical Aberrations, Sharpness & MTF
  chromaticAberration: number; // 0..1 lateral/longitudinal CA
  sphericalAberration: number; // 0..1 wide-open glow
  centerSharpness: number; // 0..1
  cornerSoftness: number; // 0..1 coma / astigmatism falloff
  veilingGlare: number; // 0..1 vintage low-contrast shadow lift
  spectralTransmissionRgb: [number, number, number]; // Spectral tint multiplier
  colorWarmthShift: number; // -0.5..0.5 transmission warmth
  // 4. Bokeh & Defocus Simulation
  irisBlades: number;
  bladeCurvature: number; // 0 = straight polygonal blades, 1 = rounded circular iris
  bokehSwirl: number; // -1..1 Petzval / cat's eye swirl factor
  catsEyeFactor: number; // 0..1 mechanical housing clipping at frame edges
  bokehRimBrightness: number; // -0.5..0.8 (- apodized soft edge, + overcorrected bright soap-bubble rim)
  onionRingIntensity: number; // 0..1 molded aspherical concentric rings inside bokeh
  // 6. Lens Flare & Ghosting
  coatingType: string;
  flareIntensity: number; // 0..1
  flareTint: [number, number, number]; // RGB coating reflection tint
  ghostCount: number; // Internal element reflection count (e.g. 4..12)
  // 7. Focus & Mechanical Characteristics
  focusThrowDeg: number; // e.g. 300 deg cinema gear throw
  irisThrowDeg: number; // e.g. 90 deg
  focusBreathingFactor: number; // 0..0.5
  anamorphicMumpsFactor: number; // 0..0.4 close-focus horizontal squeeze change
  elementCount: number;
  groupCount: number;
  frontDiameterMm: number;
  weightKg: number;
  // 10. Calibration Accuracy Provenance
  calibrationAccuracy: {
    opticalGeometry: CalibrationAccuracyLevel;
    mtfAndDistortion: CalibrationAccuracyLevel;
    bokehAndFlareModel: CalibrationAccuracyLevel;
  };
  summary: string;
}

